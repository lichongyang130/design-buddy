import fs from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { Converter } from 'opencc-js/cn2t'
import { build } from 'esbuild'
const root = new URL('../', import.meta.url)
const traditional = Converter({ from: 'cn', to: 'tw' })
const rows = (await fs.readFile(new URL('src/ui-language-strings.txt', root), 'utf8')).trim().split('\n').map(line => {
  const [zh, en, ja] = line.split('|')
  if (!zh || !en || !ja) throw Error('Incomplete UI translation: ' + line)
  return { zh, en, ja, 'zh-TW': traditional(zh) }
})
await fs.writeFile(new URL('src/ui-language-generated.js', root), '// Generated by scripts/build-ui-language.mjs. Edit ui-language-strings.txt.\nexport default ' + JSON.stringify(rows, null, 2) + '\n')
await build({ entryPoints: [new URL('src/detail-language-entry.js', root).pathname], bundle: true, minify: true, format: 'esm', outfile: new URL('public/atelier/detail-shell/language.js', root).pathname })
const folder = new URL('public/atelier/detail-shell/', root), files = []
for (const path of ['app.js', 'style.css', 'language.js']) {
  const bytes = await fs.readFile(new URL(path, folder))
  files.push({ path, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') })
}
await fs.writeFile(new URL('asset-manifest.json', folder), JSON.stringify({ schemaVersion: 1, files }, null, 2) + '\n')
console.log(`Built ${rows.length} four-language UI entries and standalone detail localization.`)
